/**
 * Downloads the exact web-font files the design export loads from Google Fonts
 * (same CSS URL, Chrome's user agent) into public/fonts and writes
 * src/app/fonts.css with matching @font-face rules.
 *
 * Run once with `npm run fonts` — the output is committed, so builds never hit Google.
 * All three families are licensed under the SIL Open Font License.
 */
import fs from "node:fs/promises";
import path from "node:path";

// Identical to the <link> in assets/html/Main.dc.html
const CSS_URL =
  "https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,300..800&family=Instrument+Serif:ital@0;1&family=DM+Mono:wght@400;500&display=swap";
const USER_AGENT =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36";
const SUBSETS = new Set(["latin", "latin-ext"]);

const root = path.resolve(import.meta.dirname, "..");
const fontDir = path.join(root, "public", "fonts");
const cssOut = path.join(root, "src", "app", "fonts.css");

const css = await (await fetch(CSS_URL, { headers: { "User-Agent": USER_AGENT } })).text();
await fs.rm(fontDir, { recursive: true, force: true });
await fs.mkdir(fontDir, { recursive: true });

const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g)];
const rules = [];

for (const [, subset, block] of blocks) {
  if (!SUBSETS.has(subset)) continue;
  const family = block.match(/font-family: '([^']+)'/)[1];
  const style = block.match(/font-style: (\w+)/)[1];
  const weight = block.match(/font-weight: ([\d ]+);/)[1].trim();
  const url = block.match(/url\((https:[^)]+)\)/)[1];

  const file = `${family.toLowerCase().replace(/\s+/g, "-")}-${style}-${weight.replace(" ", "-")}-${subset}.woff2`;
  const data = Buffer.from(await (await fetch(url)).arrayBuffer());
  await fs.writeFile(path.join(fontDir, file), data);
  rules.push(`/* ${subset} */\n${block.replace(url, `/fonts/${file}`)}`);
  console.log(`${file}  ${data.length} bytes`);
}

await fs.writeFile(
  cssOut,
  `/* Generated by scripts/fetch-fonts.mjs — do not edit by hand.\n   Same files the design export loads from Google Fonts. */\n\n${rules.join("\n")}\n`,
);
console.log(`wrote ${path.relative(root, cssOut)} (${rules.length} faces)`);
